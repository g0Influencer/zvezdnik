/**
 * Apply sheet-sourced bodies on top of the static topic list. Topics with no
 * sheet content keep their hardcoded fallback body.
 */
export function applySheetBodies(
  topics: LongreadTopic[],
  sheetBodies: Partial<Record<string, string>>
): LongreadTopic[] {
  return topics.map((t) => {
    const col = LONGREAD_TOPIC_TO_SHEET[t.id];
    const sheetText = col ? sheetBodies[col]?.trim() : '';
    if (!sheetText) return t;
    const paragraphs = sheetText
      .replace(/\r\n/g, '\n')
      .split(/\n{2,}|\n/)
      .map((p) => p.trim())
      .filter(Boolean);
    return { ...t, body: paragraphs };
  });
}
