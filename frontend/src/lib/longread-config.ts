export function getTopicsForUser(
  personalization?: Record<string, unknown> | null
): LongreadTopic[] {
  const selectedAreas = (personalization?.selectedAreas as string[]) || [];

  // Order: weekly (PRO) → natal chart (free) → other-person-chart (PRO) → inner resource (free) → остальные по релевантности (PRO).
  const weekly = LONGREAD_TOPICS.find((t) => t.id === 'weekly-longread')!;
  const natalChart = LONGREAD_TOPICS.find((t) => t.id === 'natal-chart')!;
  const otherPerson = LONGREAD_TOPICS.find((t) => t.id === 'other-person-chart')!;
  const innerResource = LONGREAD_TOPICS.find((t) => t.id === 'inner-resource')!;
  const excludedIds = new Set(['natal-chart', 'weekly-longread', 'inner-resource', 'other-person-chart']);
  const others = LONGREAD_TOPICS.filter((t) => !excludedIds.has(t.id));

  const sortedOthers =
    selectedAreas.length === 0
      ? [...others]
      : [...others].sort((a, b) => {
          const aRel = a.linkedAreas.filter((area) => selectedAreas.includes(area)).length;
          const bRel = b.linkedAreas.filter((area) => selectedAreas.includes(area)).length;
          return bRel - aRel;
        });

  return [weekly, natalChart, otherPerson, innerResource, ...sortedOthers];
}

export function renderLongreadBody(
  body: string[],
  vars: { name?: string | null; sign?: string; symbol?: string }
): string[] {
  const name = vars.name?.trim() || 'друг';
  const sign = vars.sign || '';
  const symbol = vars.symbol || '';
  return body.map((p) =>
    p.split('{name}').join(name).split('{sign}').join(sign).split('{symbol}').join(symbol)
  );
}

