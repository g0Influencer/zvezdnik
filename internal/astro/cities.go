// LookupCity returns coordinates for a known city by name (Russian or English).
// Case-insensitive, trims whitespace. Returns ok=false if not found.
func LookupCity(name string) (lat, lon float64, ok bool) {
	key := strings.ToLower(strings.TrimSpace(name))
	if c, found := cityCoords[key]; found {
		return c[0], c[1], true
	}
	return 0, 0, false
}
